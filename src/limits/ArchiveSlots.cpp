// Makes room in CStreaming::ms_files for more than two imported cities, by moving the archive
// table somewhere bigger. It is the limit that stops a third region dead: with eight slots the log
// reads "7/8 slots used" with only Vice City and Liberty City in, and there is no eighth.
//
// THE TABLE. CStreaming::ms_files is 8 x 0x30 at 0x8E48D8, ending at 0x8E4A58:
//
//     +0x00  char name[0x28]      the archive path, game-relative
//     +0x28  bool notPlayerImg
//     +0x2C  int  streamHandle    CdStreamOpen's return - the stream index, already shifted << 24
//
// San Andreas spends six of the eight before a region is ever asked for: gta3 and gta_int in
// CStreaming::InitImageList, carrec, script and cutscene from gta.dat, and player.img in
// CGame::Init2. Two cities take it to eight, and CStreaming::AddImageToList's answer to a full
// table is to return slot 0 - so a third region's archive would not fail, it would silently be
// read as gta3.img.
//
// WHERE THE CEILING REALLY IS, and why this stops at 32. ms_files is not the only fixed array in
// the path. CdStreamOpen (a HOODLUM stub at 0x1564A90, entered from 0x4067B0) scans
// gStreamFileHandles - 32 dwords at 0x8E4010 - for a free handle, `cmp esi, 0x20; jl`, and copies
// the name into gStreamNames, 32 x 0x40 at 0x8E4098. It returns the index shifted left 24, and
// CdStreamRead (0x156C2C0, from 0x406A20) takes that back apart with `shr edx, 0x18` and indexes
// gStreamFileHandles with it. So the encoding itself would carry 256 archives and the byte
// CStreamingInfo keeps the image id in (+0x7, read with movzx at 0x407570) would too - but the two
// CdStream arrays are 32 entries, and a 33rd would write its handle over gNumChannels at 0x8E4090
// and its name over the global at 0x8E4898. 32 is therefore the honest ceiling for this change,
// and 32 is what it takes. Going past it means moving those two arrays as well; they have few
// sites, and 255 is the structural wall behind them.
//
// THE TRAP, the same one PickupSlots met. 0x8E4A58 is one past the last entry AND a live global in
// its own right - CStreaming reads and writes it as a byte in six places - and 0x8E4A60 is
// ms_channels, whose index-to-pointer arithmetic (`add edi, 0x8E4A60`) is an immediate in exactly
// the window an end-of-array bound falls in. So "every instruction naming 0x8E4A58" is the wrong
// question. An end bound here is an IMMEDIATE that a `cmp` closes a walk over the table with, and
// it names a real field of the entry one past the last; tools/scan_archive_slot_sites.py applies
// that rule and prints everything it rejects, and tools/verify_archive_slot_sites.py re-reads both
// halves out of the executable and checks that none of the rejected addresses is in either table.
//
// THE SPARE ENTRY. CStreaming::LoadCdDirectory reads the NEXT entry's first byte before it checks
// its cursor against the end - `mov al, [esi+0x30]` at 0x5B8318, then `cmp esi, end` at the top of
// the loop - so a full table is read one entry past its end. The block therefore holds Count() + 1
// entries and the spare is left zeroed, which is also what stops the loop.
//
// SIGNED BOUNDS. Every one of those walks compares with `jl` or `jge`, so the table has to sit
// below 0x80000000 for the comparisons to mean what they say. gta_sa.exe is
// IMAGE_FILE_LARGE_ADDRESS_AWARE, so on a 64-bit Windows the heap can hand back an address above
// that; the block is checked and given back rather than used if it does.
//
// SAVEGAMES. Nothing here touches one. No block CGenericGameStorage::GenericSave writes mentions
// ms_files - the streaming block (0x5D29A0) is a byte per model slot out of ms_aInfoForModel, and
// the image id lives in that array's +0x7, not in a saved field. Archive slots are assigned fresh
// on every start from the ini's order, exactly as they were with eight.
#include <plugin.h>
#include <cstdint>
#include <cstdlib>
#include <iterator>
#include "ArchiveSlots.h"
#include "Settings.h"
#include "Log.h"

using namespace plugin;

namespace {

constexpr uintptr_t kArray = 0x8E48D8;     // CStreaming::ms_files
constexpr unsigned kStride = 0x30;         // sizeof(tStreamingFileDesc)
constexpr int kVanillaCount = 8;
constexpr uintptr_t kArrayEnd = kArray + (uintptr_t)kVanillaCount * kStride;   // 0x8E4A58

// gStreamFileHandles[32] at 0x8E4010 and gStreamNames[32][0x40] at 0x8E4098 are what CdStreamOpen
// hands out of, and neither is bounds-checked. See the header comment.
constexpr int kMaxCount = 32;

// ---------------------------------------------------------------- the sites
//
// Generated by tools/scan_archive_slot_sites.py and checked by tools/verify_archive_slot_sites.py.
// `operandOffset` is where the four bytes sit inside the instruction; `field` is the offset within
// an entry that the operand names, so a site keeps naming the same field of the same entry.

struct Site { uint32_t address; uint8_t operandOffset; uint8_t field; };

// A dword naming &ms_files[0].<field>. Rewritten to the new base plus the same field offset.
const Site kBaseSites[] = {
    { 0x040757D, 2, 0x2C },   // CStreamingInfo::GetCdPosn     mov eax, [eax + streamHandle]
    { 0x04083C0, 1, 0x2C },   // CStreaming::InitImageList     the clear loop's cursor
    { 0x04083E8, 1, 0x00 },   //                               first free-slot search
    { 0x040840A, 1, 0x00 },   //                               second free-slot search
    { 0x0408439, 2, 0x00 },   //                               gta3.img's name, index -> pointer
    { 0x0408459, 2, 0x2C },   //                               its handle
    { 0x040845F, 2, 0x28 },   //                               its notPlayerImg
    { 0x0408477, 2, 0x00 },   //                               gta_int.img's name
    { 0x04084A0, 2, 0x2C },   //                               its handle
    { 0x04084A6, 2, 0x28 },   //                               its notPlayerImg
    { 0x0408FDA, 2, 0x2C },   // CStreaming::GetNextFileOnCd   mov eax, [edx + streamHandle]
    { 0x0409D58, 2, 0x2C },   // CStreaming::RequestSpecialModel
    { 0x040CC52, 2, 0x2C },   // CStreaming::RequestModelStream
    { 0x040CCC5, 2, 0x2C },   //                               and its second read
    { 0x05B82F0, 1, 0x00 },   // CStreaming::LoadCdDirectory   "is slot 0 in use at all"
    { 0x05B82FC, 1, 0x00 },   //                               the walk's cursor

    // --- whole functions HOODLUM moved out of .text into its own section, reached by the jmp
    // thunks the game still calls. The stub each one belongs to was found from that thunk.
    { 0x1560E66, 2, 0x2C },   // CStreamingInfo::GetCdPosnAndSize (0x1560E50, from 0x4075A0)
    { 0x15663E5, 2, 0x2C },   // CStreaming::RequestFile          (0x15663B0, from 0x40A080)
    { 0x1567B93, 1, 0x00 },   // CStreaming::AddImageToList       (0x1567B90, from 0x407610):
    { 0x1567BB8, 2, 0x00 },   //   the free-slot search, then the name, the handle and the flag
    { 0x1567BD4, 2, 0x2C },   //   of the slot it settled on
    { 0x1567BE1, 2, 0x28 },
};

// An immediate naming &ms_files[8].<field> - one past the last entry - that a `cmp` closes a walk
// over the table with. Rewritten to the new base plus the new count times the stride.
const Site kEndSites[] = {
    { 0x04083DD, 1, 0x2C },   // CStreaming::InitImageList     the clear loop
    { 0x04083F9, 1, 0x00 },   //                               first free-slot search
    { 0x0408419, 1, 0x00 },   //                               second free-slot search
    { 0x05B8301, 2, 0x00 },   // CStreaming::LoadCdDirectory
    { 0x1567BA1, 1, 0x00 },   // CStreaming::AddImageToList    (HOODLUM's copy)
};

uint8_t* gBlock = nullptr;
int gCount = kVanillaCount;

uint32_t BaseValue(const Site& s, uintptr_t base) { return (uint32_t)(base + s.field); }
uint32_t EndValue(const Site& s, uintptr_t base, int count) {
    return (uint32_t)(base + (uintptr_t)count * kStride + s.field);
}

bool Holds(uintptr_t address, uint8_t operandOffset, uint32_t expected) {
    uint32_t have = (uint32_t)patch::GetUInt(address + operandOffset);
    if (have == expected) return true;
    Log::Write("ERROR: the archive table was not enlarged: 0x%X holds 0x%08X, expected 0x%08X "
               "(another mod has patched it, or this is not the 1.0 US executable); San Andreas "
               "keeps its %d archive slots and a region past the second gets none",
               (unsigned)(address + operandOffset), have, expected, kVanillaCount);
    return false;
}

}   // namespace

namespace ArchiveSlots {

int VanillaCount() { return kVanillaCount; }
int MaxCount() { return kMaxCount; }
int Count() { return gCount; }
bool Moved() { return gBlock != nullptr; }
uintptr_t Base() { return gBlock ? (uintptr_t)gBlock : kArray; }
unsigned Stride() { return kStride; }

int Used() {
    int used = 0;
    for (int i = 0; i < gCount; i++)
        if (*reinterpret_cast<char*>(Base() + (uintptr_t)i * kStride)) used++;
    return used;
}

void Install() {
    if (gBlock) return;

    int wanted = Settings::world.archiveSlotLimit;
    if (wanted < 0) wanted = kMaxCount;
    if (wanted <= kVanillaCount) {
        if (wanted >= 0 && wanted < kVanillaCount)
            Log::Write("ArchiveSlotLimit %d is below San Andreas' own %d; left alone",
                       wanted, kVanillaCount);
        return;
    }
    if (wanted > kMaxCount) {
        Log::Write("ArchiveSlotLimit %d clamped to %d: CdStreamOpen hands out of a 32-entry file "
                   "table of its own and does not check it", wanted, kMaxCount);
        wanted = kMaxCount;
    }
    if (Settings::RunningUnderSaMp()) {
        Log::Write("SA-MP: the archive table stays at %d slots, the server owns the streamer",
                   kVanillaCount);
        return;
    }
    // InitImageList has already run if anything is registered, and moving the table under a live
    // stream handle would leave the game reading gta3.img out of a block full of zeroes.
    if (*reinterpret_cast<char*>(kArray)) {
        Log::Write("ERROR: the archive table was not enlarged: archive 0 is already registered, so "
                   "the streamer is past CStreaming::InitImageList");
        return;
    }

    for (const Site& s : kBaseSites)
        if (!Holds(s.address, s.operandOffset, BaseValue(s, kArray))) return;
    for (const Site& s : kEndSites)
        if (!Holds(s.address, s.operandOffset, EndValue(s, kArray, kVanillaCount))) return;

    // One entry more than the count: CStreaming::LoadCdDirectory reads the next entry's first byte
    // before it checks its cursor against the end, so a full table is read one entry past it.
    uint8_t* block = (uint8_t*)calloc((size_t)wanted + 1, kStride);
    if (!block) {
        Log::Write("ERROR: the archive table was not enlarged: cannot allocate %d slots", wanted);
        return;
    }
    // Every walk over the table compares its cursor with `jl` or `jge`, and gta_sa.exe is
    // LARGE_ADDRESS_AWARE, so a block above 2GB would make each of those loops read the wrong way.
    uintptr_t end = (uintptr_t)block + ((size_t)wanted + 1) * kStride;
    if (end >= 0x80000000u) {
        free(block);
        Log::Write("ERROR: the archive table was not enlarged: the heap gave back %p, and the "
                   "loops that walk the table compare their cursor as a signed integer",
                   (void*)block);
        return;
    }

    const uintptr_t base = (uintptr_t)block;
    for (const Site& s : kBaseSites)
        patch::SetUInt(s.address + s.operandOffset, BaseValue(s, base));
    for (const Site& s : kEndSites)
        patch::SetUInt(s.address + s.operandOffset, EndValue(s, base, wanted));

    int wrong = 0;
    for (const Site& s : kBaseSites)
        if ((uint32_t)patch::GetUInt(s.address + s.operandOffset) != BaseValue(s, base)) wrong++;
    for (const Site& s : kEndSites)
        if ((uint32_t)patch::GetUInt(s.address + s.operandOffset) != EndValue(s, base, wanted)) wrong++;
    if (wrong) {
        for (const Site& s : kBaseSites)
            patch::SetUInt(s.address + s.operandOffset, BaseValue(s, kArray));
        for (const Site& s : kEndSites)
            patch::SetUInt(s.address + s.operandOffset, EndValue(s, kArray, kVanillaCount));
        free(block);
        Log::Write("ERROR: the archive table was not enlarged: %d site(s) did not take the new "
                   "value; the original values have been put back", wrong);
        return;
    }

    gBlock = block;
    gCount = wanted;
    Log::Write("archive slots: CStreaming::ms_files %d -> %d entries at %p (%u site(s) patched); "
               "San Andreas spends six on gta3, gta_int, carrec, script, cutscene and player.img, "
               "so %d are left for the regions",
               kVanillaCount, wanted, (void*)block,
               (unsigned)(std::size(kBaseSites) + std::size(kEndSites)), wanted - 6);
}

}   // namespace ArchiveSlots
