#!/usr/bin/env python3
"""Turn tools/model_limit_sites.txt into the constexpr table src/ModelLimitSites.h.

Usage: gen_model_limit_sites.py [inventory] [header]
"""
import sys

KINDS = {
    "info": "kInfoArray", "ptr": "kPtrArray", "atomic": "kAtomicStore", "time": "kTimeStore",
    "res": "kResourceBase", "resneg": "kResourceBaseNeg", "count4": "kCountTimes4",
    "sentinel16": "kSentinelIndex",
}


def read(path):
    rows = []
    for line in open(path):
        if line.startswith("#") or not line.strip():
            continue
        f = [p.strip() for p in line.split("|")]
        rows.append((int(f[0], 16), KINDS[f[1]], int(f[2].lstrip("+")), int(f[3]),
                     int(f[4], 16), int(f[5]), f[6], f[7]))
    return rows


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else "tools/model_limit_sites.txt"
    dst = sys.argv[2] if len(sys.argv) > 2 else "src/ModelLimitSites.h"
    rows = read(src)
    counts = {}
    for r in rows:
        counts[r[1]] = counts.get(r[1], 0) + 1
    with open(dst, "w") as out:
        out.write("// Generated by tools/gen_model_limit_sites.py from tools/model_limit_sites.txt.\n")
        out.write("// Every instruction in gta_sa.exe 1.0 US that names one of the streaming arrays or a\n")
        out.write("// resource id base, with the operand byte to rewrite and the value it must still hold.\n")
        out.write("// Do not edit by hand; re-run the scanner and the generator instead.\n")
        out.write("#pragma once\n#include <cstdint>\n\nnamespace ModelLimits {\n\n")
        out.write("enum SiteKind : uint8_t {\n")
        for name in ("kInfoArray", "kPtrArray", "kAtomicStore", "kTimeStore", "kResourceBase",
                     "kResourceBaseNeg", "kCountTimes4", "kSentinelIndex", "kSiteKindCount"):
            out.write("    %s,\n" % name)
        out.write("};\n\n")
        out.write("struct Site {\n"
                  "    uint32_t address;\n"
                  "    uint32_t oldValue;\n"
                  "    uint8_t  operandOffset;  // bytes from the instruction start to the operand\n"
                  "    uint8_t  operandSize;\n"
                  "    uint8_t  kind;\n"
                  "    uint8_t  scale;          // resource-base multiplier folded into the operand\n"
                  "};\n\n")
        out.write("// %d sites: %s\n" % (len(rows), ", ".join(f"{k}={v}" for k, v in sorted(counts.items()))))
        out.write("constexpr Site kSites[] = {\n")
        for addr, kind, off, size, old, scale, fn, note in rows:
            out.write("    { 0x%X, 0x%08X, %d, %d, %s, %d },\n" % (addr, old, off, size, kind, scale))
        out.write("};\n\n}\n")
    print("%s: %d sites" % (dst, len(rows)))
    for k, v in sorted(counts.items()):
        print("  %-18s %d" % (k, v))


if __name__ == "__main__":
    main()
